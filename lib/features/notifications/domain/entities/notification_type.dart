enum NotificationType {
  attendanceClockedIn,
  attendanceClockedOut,
  leaveRequestCreated,
  leaveRequestApproved,
  leaveRequestRejected,
  shiftAssigned,
  shiftUpdated,
  shiftCancelled,
  shiftReminder,
  chatMessage,
  teamAnnouncement,
  attendanceCorrectionCreated,
  attendanceCorrectionReviewed,
  shiftExchangeRequested,
  shiftExchangeUpdated,
  fixedShiftReminder,
  clockOutReminder,
  unknown;

  static NotificationType parse(Object? value) => switch (value) {
    'ATTENDANCE_CLOCKED_IN' => attendanceClockedIn,
    'ATTENDANCE_CLOCKED_OUT' => attendanceClockedOut,
    'LEAVE_REQUEST_CREATED' => leaveRequestCreated,
    'LEAVE_REQUEST_APPROVED' => leaveRequestApproved,
    'LEAVE_REQUEST_REJECTED' => leaveRequestRejected,
    'SHIFT_ASSIGNED' => shiftAssigned,
    'SHIFT_UPDATED' => shiftUpdated,
    'SHIFT_CANCELLED' => shiftCancelled,
    'SHIFT_REMINDER' => shiftReminder,
    'CHAT_MESSAGE' => chatMessage,
    'TEAM_ANNOUNCEMENT' => teamAnnouncement,
    'ATTENDANCE_CORRECTION_CREATED' => attendanceCorrectionCreated,
    'ATTENDANCE_CORRECTION_REVIEWED' => attendanceCorrectionReviewed,
    'SHIFT_EXCHANGE_REQUESTED' => shiftExchangeRequested,
    'SHIFT_EXCHANGE_UPDATED' => shiftExchangeUpdated,
    'FIXED_SHIFT_REMINDER' => fixedShiftReminder,
    'CLOCK_OUT_REMINDER' => clockOutReminder,
    _ => unknown,
  };

  String? get apiValue => switch (this) {
    attendanceClockedIn => 'ATTENDANCE_CLOCKED_IN',
    attendanceClockedOut => 'ATTENDANCE_CLOCKED_OUT',
    leaveRequestCreated => 'LEAVE_REQUEST_CREATED',
    leaveRequestApproved => 'LEAVE_REQUEST_APPROVED',
    leaveRequestRejected => 'LEAVE_REQUEST_REJECTED',
    shiftAssigned => 'SHIFT_ASSIGNED',
    shiftUpdated => 'SHIFT_UPDATED',
    shiftCancelled => 'SHIFT_CANCELLED',
    shiftReminder => 'SHIFT_REMINDER',
    chatMessage => 'CHAT_MESSAGE',
    teamAnnouncement => 'TEAM_ANNOUNCEMENT',
    attendanceCorrectionCreated => 'ATTENDANCE_CORRECTION_CREATED',
    attendanceCorrectionReviewed => 'ATTENDANCE_CORRECTION_REVIEWED',
    shiftExchangeRequested => 'SHIFT_EXCHANGE_REQUESTED',
    shiftExchangeUpdated => 'SHIFT_EXCHANGE_UPDATED',
    fixedShiftReminder => 'FIXED_SHIFT_REMINDER',
    clockOutReminder => 'CLOCK_OUT_REMINDER',
    unknown => null,
  };
}
